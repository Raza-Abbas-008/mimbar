bool isUr(BuildContext c) => Localizations.localeOf(c).languageCode == 'ur';

/// Looks up a UI string in the current locale. Widgets calling this depend on
/// the Localizations scope, so they rebuild when the language is toggled.
String tr(BuildContext c, String key) => trL(isUr(c), key);

String trL(bool ur, String key) => (ur ? _ur : _en)[key] ?? _en[key] ?? key;

String typeLabel(EventType t, bool ur) => trL(ur, 'type_${t.name}');

String statusLabel(EventStatus s, bool ur) => trL(ur, 'status_${s.name}');

String seriesLabel(int n, bool ur) => trL(ur, 'series_$n');

String leadLabel(int min, bool ur) {
  if (min % 1440 == 0) {
    final d = min ~/ 1440;
    if (d == 7) return trL(ur, 'lead_week');
    return '$d ${trL(ur, d == 1 ? 'lead_day' : 'lead_days')}';
  }
  if (min % 60 == 0) {
    final h = min ~/ 60;
    return '$h ${trL(ur, h == 1 ? 'lead_hour' : 'lead_hours')}';
  }
  return '$min ${trL(ur, 'lead_min')}';
}

String durationLabel(int min, bool ur) {
  final h = min ~/ 60, m = min % 60;
  final parts = <String>[
    if (h > 0) '$h ${trL(ur, h == 1 ? 'lead_hour' : 'lead_hours')}',
    if (m > 0) '$m ${trL(ur, 'lead_min')}',
  ];
  return parts.join(' ');
}

